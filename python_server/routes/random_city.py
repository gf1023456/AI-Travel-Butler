@router.get("/random-city")
async def get_random_city():
    """随机返回一个旅行城市"""
    city = random.choice(CHINA_CITIES)
    return {
        "code": 0,
        "data": {
            "name": city["name"],
            "province": city["province"],
            "tags": city["tags"],
            "desc": city["desc"]
        }
    }


@router.get("/random-cities")
async def get_random_cities(count: int = 6):
    """随机返回多个旅行城市（用于转盘）"""
    count = min(max(count, 1), 20)  # 限制 1~20
    selected = random.sample(CHINA_CITIES, min(count, len(CHINA_CITIES)))
    return {
        "code": 0,
        "data": [
            {
                "name": c["name"],
                "province": c["province"],
                "tags": c["tags"],
                "desc": c["desc"]
            }
            for c in selected
        ],
        "total": len(CHINA_CITIES)
    }
